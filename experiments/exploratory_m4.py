"""M4 exploratory sensitivity analysis (EXPLORATORY, post hoc, 2026-11-25).

Written after the confirmatory EXP-002 and EXP-003 outputs were seen. It
re-reads the committed per-run results (no new simulation) and never changes
or replaces a frozen verdict. Outputs go to results/exploratory/M4-sensitivity/.

Questions (all aimed at the phase confound, limitation 13):

- X1 change score: paired A1 - A0 difference in (phi_post - phi_pre), pooled
  over cells with the frozen bootstrap settings. It removes each run's own
  pre-shock level from the outcome.
- X2 cell subsets: Delta on phi_post over the 8 cells where A0 is orderable
  (rule R-BI) and over the 10 flagged cells.
- X3 matched pre-shock order: cells where the cell-mean phi_pre of A1 and A0
  differ by less than 0.05 (the SESOI), chosen on pre-shock values only.
- X4 early shock response from the stored phi series: drop = phi_pre - mean
  phi over [t_d, t_d + 50); retained = (mean phi over [t_d, t_d + 50) - b) /
  (phi_pre - b), with b = sqrt(pi) / (2 sqrt(N)) the expected polarization of
  N independent uniform headings. Reported only where both arms have
  phi_pre > 2b in the cell mean (retained is unstable near b).
- X5 the same change score (X1) for the EXP-003 conditions.
- Integrity: SHA-256 of every raw run file against raw_manifest.json.

  .venv/bin/python experiments/exploratory_m4.py
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))

import analyse_confirmatory as ac  # noqa: E402
from swarm.manifest import environment, utc_now  # noqa: E402
from swarm.runner import load_results  # noqa: E402

OUT = ROOT / "results" / "exploratory" / "M4-sensitivity"
EARLY = 50


def raw_integrity(d: Path) -> dict:
    man = json.loads((d / "raw_manifest.json").read_text(encoding="utf-8"))
    items = list(man["sha256"].items())
    bad = []
    for path, sha in items:
        p = d / path
        if not p.exists() or hashlib.sha256(p.read_bytes()).hexdigest() != sha:
            bad.append(str(path))
    return {"files": len(items), "mismatched_or_missing": bad}


def derived(records: list[dict]) -> None:
    """Attach exploratory per-run quantities under r['metrics'] (in memory only)."""
    for r in records:
        if r["status"] != "ok":
            continue
        c = r["config"]
        phi = np.asarray(r["series"]["phi"], dtype=float)
        td = int(c["t_disturb"])
        m = r["metrics"]
        early = float(phi[td:td + EARLY].mean())
        b = math.sqrt(math.pi) / (2 * math.sqrt(int(c["n_agents"])))
        m["x_change"] = m["phi_post"] - m["phi_pre"]
        m["x_drop"] = m["phi_pre"] - early
        m["x_retained"] = (early - b) / (m["phi_pre"] - b) if m["phi_pre"] > b else None


def summary(b: dict) -> dict:
    return {k: b[k] for k in ("estimate", "ci_low", "ci_high", "n_cells", "n_pairs")}


def _ci(b: dict) -> str:
    return f"{b['estimate']:.3f} [{b['ci_low']:.3f}, {b['ci_high']:.3f}]"


def render(res: dict) -> str:
    x = res["results"]
    lines = ["<!-- SPDX-License-Identifier: LicenseRef-SWARM-NC-Research-1.0 -->",
             "# M4 exploratory sensitivity (EXPLORATORY, post hoc)", "",
             "Generated by `experiments/exploratory_m4.py` from the committed per-run results of EXP-002 and "
             "EXP-003 (no new simulation). Written after the confirmatory outputs were seen, so nothing here is "
             "confirmatory and nothing here changes a frozen verdict. Bootstrap as frozen (stratified by cell, "
             f"{res['bootstrap']['n_boot']} resamples, seed {res['bootstrap']['seed']}, 95% percentile CI).", "",
             "| id | quantity (A1 - A0 unless stated) | cells / pairs | estimate [95% CI] |",
             "| --- | --- | --- | --- |"]
    rows = [("X1", "change score phi_post - phi_pre, all cells", x["X1_change_score_all"]),
            ("X1", "change score, 8 orderable cells", x["X1_change_score_orderable8"]),
            ("X1", "change score, 10 flagged cells", x["X1_change_score_flagged10"]),
            ("X2", "phi_post, 8 orderable cells", x["X2_phi_post_orderable8"]),
            ("X2", "phi_pre, 8 orderable cells", x["X2_phi_pre_orderable8"]),
            ("X2", "phi_post, 10 flagged cells", x["X2_phi_post_flagged10"]),
            ("X3", "phi_post, cells with matched pre-shock order", x["X3_phi_post_matched"]),
            ("X3", "phi_pre, cells with matched pre-shock order", x["X3_phi_pre_matched"]),
            ("X4", "early drop phi_pre - mean phi over [t_d, t_d + 50), all cells", x["X4_drop_all"])]
    if "X4_retained_informative" in x:
        rows.append(("X4", "fraction of order above random retained over [t_d, t_d + 50), informative cells",
                     x["X4_retained_informative"]))
    for name, e in x["X5_exp003_change_score"].items():
        rows.append(("X5", f"change score, {name}", e["change_score"]))
    for i, q, b in rows:
        lines.append(f"| {i} | {q} | {b['n_cells']} / {b['n_pairs']} | {_ci(b)} |")
    lines += ["", f"X3 cells (|mean phi_pre A1 - A0| < 0.05): {'; '.join(x['X3_matched_cells'])}.", "",
              f"X4 random level b = {x['X4_random_level_b']:.4f}; informative cells (both arms' mean phi_pre > 2b): "
              f"{len(x['X4_informative_cells'])} of 18.", "",
              "Raw integrity (SHA-256 of every file listed in each raw_manifest.json): " + "; ".join(
                  f"{k} {v['files']} files, {len(v['mismatched_or_missing'])} mismatched or missing"
                  for k, v in res["raw_integrity"].items()) + ".", ""]
    return "\n".join(lines)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    res = {"label": "exploratory (post hoc, M4); never replaces a frozen verdict",
           "generated": utc_now(), "environment": environment(),
           "bootstrap": {"n_boot": ac.N_BOOT, "seed": ac.BOOT_SEED, "level": 0.95},
           "early_window_steps": EARLY}
    res["raw_integrity"] = {"EXP-002": raw_integrity(ac.EXP002),
                            **{f"EXP-003-{k}": raw_integrity(v) for k, v in ac.EXP003.items()}}
    exp2 = load_results(ac.EXP002)
    derived(exp2)
    flagged = ac.not_orderable()
    v = {(a, m): ac.values(exp2, a, m) for a in ("A0", "A1") for m in
         ("phi_pre", "phi_post", "x_change", "x_drop", "x_retained")}
    cells = sorted(v[("A0", "phi_post")])
    orderable = [c for c in cells if c not in flagged]

    def contrast(metric, sub=None):
        return ac.pair(v[("A1", metric)], v[("A0", metric)], cells=None if sub is None else set(sub))

    x = {}
    x["X1_change_score_all"] = summary(ac.boot(contrast("x_change")))
    x["X1_change_score_orderable8"] = summary(ac.boot(contrast("x_change", orderable)))
    x["X1_change_score_flagged10"] = summary(ac.boot(contrast("x_change", flagged)))
    x["X2_phi_post_orderable8"] = summary(ac.boot(contrast("phi_post", orderable)))
    x["X2_phi_post_flagged10"] = summary(ac.boot(contrast("phi_post", flagged)))
    x["X2_phi_pre_orderable8"] = summary(ac.boot(contrast("phi_pre", orderable)))
    mean = {k: {c: float(np.mean(list(vals.values()))) for c, vals in d.items()} for k, d in v.items()}
    matched = [c for c in cells if abs(mean[("A1", "phi_pre")][c] - mean[("A0", "phi_pre")][c]) < ac.SESOI]
    x["X3_matched_cells"] = [ac.cell_label(c) for c in matched]
    x["X3_phi_post_matched"] = summary(ac.boot(contrast("phi_post", matched)))
    x["X3_phi_pre_matched"] = summary(ac.boot(contrast("phi_pre", matched)))
    b = math.sqrt(math.pi) / (2 * math.sqrt(200))
    informative = [c for c in cells if min(mean[("A0", "phi_pre")][c], mean[("A1", "phi_pre")][c]) > 2 * b]
    x["X4_random_level_b"] = b
    x["X4_informative_cells"] = [ac.cell_label(c) for c in informative]
    x["X4_drop_all"] = summary(ac.boot(contrast("x_drop")))
    if informative:
        x["X4_retained_informative"] = summary(ac.boot(contrast("x_retained", informative)))
    rows = []
    for c in cells:
        rows.append({"cell": ac.cell_label(c), "a0_not_orderable_flag": c in flagged,
                     **{f"{a}_{m}_mean": mean[(a, m)].get(c) for a in ("A0", "A1")
                        for m in ("phi_pre", "phi_post", "x_change", "x_drop", "x_retained")},
                     "A1-A0_change_mean": float(contrast("x_change", [c])[c].mean())})
    x["per_cell"] = rows
    # X5: EXP-003 conditions, change score
    a0_exp2 = {m: ac.values(exp2, "A0", m) for m in ("x_change", "phi_pre")}
    x5 = {}
    for name, d in ac.EXP003.items():
        recs = load_results(d)
        derived(recs)
        if name == "S2":
            for wc, sub in ((0.25, "S2a"), (1.0, "S2b")):
                pred = (lambda r, w=wc: r["config"]["w_cohesion"] == w)
                ch = ac.pair(ac.values(recs, "A1", "x_change", pred=pred), a0_exp2["x_change"], cells=set(ac.REDUCED))
                pre = ac.pair(ac.values(recs, "A1", "phi_pre", pred=pred), a0_exp2["phi_pre"], cells=set(ac.REDUCED))
                x5[sub] = {"change_score": summary(ac.boot(ch)), "phi_pre": summary(ac.boot(pre))}
        else:
            ch = ac.pair(ac.values(recs, "A1", "x_change"), ac.values(recs, "A0", "x_change"))
            x5[name] = {"change_score": summary(ac.boot(ch))}
    x5["EXP-002_reduced4"] = {"change_score": summary(ac.boot(contrast("x_change", ac.REDUCED)))}
    x["X5_exp003_change_score"] = x5
    res["results"] = x
    (OUT / "analysis.json").write_text(json.dumps(res, indent=1, default=float) + "\n", encoding="utf-8")
    (OUT / "summary.md").write_text(render(res), encoding="utf-8")
    print(json.dumps({k: val for k, val in x.items() if k != "per_cell"}, indent=1, default=float))
    print(json.dumps(res["raw_integrity"], indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
