"""Build the manuscript, supplementary and experiment-report PDFs (M6).

Uses ``swarm.report.build_pdf`` (pandoc 3.6.3 -> Typst -> typst Python
package, DL-002) with the repository root as the Typst root, so figures under
``results/`` resolve. Also regenerates ``research/paper/manuscript.tex`` with
pandoc. The intermediate ``.typ`` files are copied to ``--typ-dir`` and then
deleted; ``--png-dir`` renders every page to PNG for visual inspection.

    .venv/bin/python scripts/build_pdfs.py [--typ-dir DIR] [--png-dir DIR] [--no-tex]
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from swarm.report import PANDOC, TYPST_PYTHON, build_pdf  # noqa: E402

AUTHOR = "Mohamed Bechir Kefi"
TEX_HEADER = ("% SPDX-License-Identifier: LicenseRef-SWARM-NC-Research-1.0 (generated by pandoc 3.6.3 "
              "from manuscript.md; do not edit by hand)\n")
DOCS = [
    "research/paper/manuscript.md",
    "research/paper/supplementary.md",
    "research/experiments/EXP-001/report.md",
    "research/experiments/EXP-002/report.md",
    "research/experiments/EXP-003/report.md",
]


def doc_title(md: Path) -> str | None:
    """YAML title if present (pandoc sets the metadata itself), else the first H1."""
    text = md.read_text(encoding="utf-8")
    if text.startswith("---"):
        m = re.search(r'^title:\s*"?(.*?)"?\s*$', text.split("---", 2)[1], re.M)
        if m:
            return None
    m = re.search(r"^# (.+)$", text, re.M)
    return m.group(1).strip() if m else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--typ-dir", type=Path, default=None)
    ap.add_argument("--png-dir", type=Path, default=None, help="render every page to PNG (60 ppi)")
    ap.add_argument("--no-tex", action="store_true")
    a = ap.parse_args()
    for rel in DOCS:
        md = ROOT / rel
        pdf = build_pdf(md, root=ROOT, title=doc_title(md), author=AUTHOR, page_numbers=True)
        typ = md.with_suffix(".typ")
        if a.png_dir:
            a.png_dir.mkdir(parents=True, exist_ok=True)
            stem = rel.replace("research/", "").replace("/", "-").replace(".md", "")
            out = str(a.png_dir / (stem + "-{p}.png"))
            code = ("import sys, typst; typst.compile(sys.argv[1], output=sys.argv[2], "
                    "root=sys.argv[3], format='png', ppi=60)")
            subprocess.run([TYPST_PYTHON, "-I", "-c", code, str(typ), out, str(ROOT)], check=True)
        if a.typ_dir:
            dest = a.typ_dir / rel.replace("/", "__").replace(".md", ".typ")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(typ, dest)
        typ.unlink()
        print(f"{rel} -> {pdf.relative_to(ROOT)} ({pdf.stat().st_size} bytes)")
    if not a.no_tex:
        paper = ROOT / "research/paper"
        subprocess.run([PANDOC, "manuscript.md", "-f", "markdown", "-t", "latex", "-s",
                        "-o", "manuscript.tex"], cwd=paper, check=True)
        tex = paper / "manuscript.tex"
        tex.write_text(TEX_HEADER + tex.read_text(encoding="utf-8"), encoding="utf-8")
        print("research/paper/manuscript.md -> research/paper/manuscript.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
